describe('checkNotes', () => {
  test('passes ordinary appearance notes', () => {
    const refused = BENIGN.map((text) => [text, checkNotes(text)] as const).filter(
      ([, result]) => !result.ok,
    )
    expect(refused).toEqual([])
  })

  test.each(REFUSED)('%p → %p', (text, code) => {
    const result = checkNotes(text)
    if (code === 'ok-normalised') {
      expect(result).toEqual({ ok: true, notes: '눈이 크게 다음 줄' })
      return
    }
    expect(result).toEqual({ ok: false, code } as never)
  })

  test('normalises full-width text and spaces', () => {
    expect(normaliseNotes('  Ｖ넥   니트 \t ')).toBe('V넥 니트')
    expect(checkNotes('  Ｖ넥   니트 ')).toEqual({ ok: true, notes: 'V넥 니트' })
  })

  test('counts Hangul syllables, not bytes', () => {
    expect(checkNotes('가'.repeat(AI_PERSON_NOTES_MAX)).ok).toBe(true)
  })
})
